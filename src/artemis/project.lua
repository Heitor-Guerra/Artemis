--- Coordinate the manifest, selected Lua runtime, and project-local LuaRocks tree.
---
--- Project owns the high-level workflow. RuntimeManager installs or reuses the
--- Lua interpreter, Lockfile preserves exact dependency resolutions, and
--- DependencyManager asks LuaRocks to install rocks into the project's local tree.
---
--- @module 'artemis.project'

local Manifest = require("artemis.manifest")
local RuntimeManager = require("artemis.runtime_manager")
local DependencyManager = require("artemis.dependency_manager")
local Lockfile = require("artemis.lockfile")
local Path = require("artemis.utils.path")
local FileSystem = require("artemis.utils.filesystem")
local Process = require("artemis.utils.process")

--- @class Artemis.ProjectOptions
--- @field manifest_path?       string                            Path to the project manifest. Defaults to artemis-project.toml.
--- @field manifest?            Artemis.Manifest                  Already-loaded manifest, useful for programmatic use and tests.
--- @field lockfile_path?       string                            Path to the lockfile. Defaults to artemis-project.lock.
--- @field cache_dir?           string                            Shared Artemis cache. Defaults to the runtime manager's cache directory.
--- @field metadata_dir?        string                            Project-local Artemis metadata directory. Defaults to .artemis.
--- @field tree?                string                            Project-local LuaRocks tree. Defaults to lua_modules.
--- @field luarocks?            string                            LuaRocks executable or project wrapper.
--- @field luarocks_config?     string                            Existing LuaRocks config to preserve.
--- @field runtime_options?     Artemis.RuntimeManagerOptions     Options passed to RuntimeManager.new().
--- @field dependency_options?  Artemis.DependencyManagerOptions  Options passed to DependencyManager.new().

--- @class Artemis.Project
--- @field root                     string                            Absolute project root directory.
--- @field manifest                 Artemis.Manifest                  Loaded project manifest.
--- @field manifest_path            string                            Absolute path to the project manifest.
--- @field runtime_manager          Artemis.RuntimeManager            Manager for the project's Lua runtime.
--- @field dependency_manager       Artemis.DependencyManager         Manager for project-local rocks.
--- @field lockfile_path            string                            Absolute path to the Artemis dependency lockfile.
--- @field lockfile?                Artemis.Lockfile                  Lockfile loaded or generated by the most recent sync.
--- @field cache_dir                string                            Shared Artemis cache directory.
--- @field metadata_dir             string                            Project-local Artemis metadata directory.
--- @field runtime_version?         string                            Exact Lua release selected for this project.
--- @field runtime_path?            string                            Path to the selected cached Lua installation.
--- @field lua_executable?          string                            Path to the selected Lua interpreter.
--- @field _dependency_options      Artemis.DependencyManagerOptions  Options used to recreate the dependency manager.
--- @field _stale_lockfile_reason?  string                            Reason the existing lockfile did not match the manifest.
local Project = {}
Project.__index = Project


------------------------------------ Local Functions ------------------------------------

--- Copy a shallow options table so callers' tables are not modified.
--- @param source?  table
--- @return table
local function copy_options(source)
    local copy = {}
    if type(source) == "table" then
        for key, value in pairs(source) do
            copy[key] = value
        end
    end
    return copy
end

--- Resolve an optional path relative to the project root.
--- @param root  string
--- @param path  string
--- @return string
local function project_path(root, path)
    if Path.is_absolute(path) then
        return path
    end

    return Path.join(root, path)
end

local function create_dependency(name, constraint)
    if type(name) ~= "string" or not name:match("%S") then
        return nil, "Dependency name must be a non-empty string."
    end

    if not name:match("^[%w][%w_.%-]*$") then
        return nil, string.format("Invalid LuaRocks package name: %s", name)
    end

    if constraint == nil then
        constraint = "*"
    end
    if type(constraint) ~= "string" or not constraint:match("%S") then
        return nil, "Dependency version constraint must be a non-empty string."
    end

    if constraint:find("[\r\n]") then
        return nil, "Dependency version constraint cannot contain line breaks."
    end

    return { name = name, constraint = constraint }
end

--- Convert a name-to-constraint map into Dependency values.
--- @param declarations  table<string, string>
--- @return Artemis.Dependency[]?  dependencies
--- @return string?                error_message
local function make_dependencies(declarations)
    local names = {}
    for name in pairs(declarations) do
        names[#names + 1] = name
    end
    table.sort(names)

    local dependencies = {}
    for _, name in ipairs(names) do
        dependencies[#dependencies + 1] = create_dependency(name, declarations[name])
    end

    return dependencies
end

--- Build direct dependencies from the current manifest declarations.
--- @param manifest  Artemis.Manifest
--- @return Artemis.Dependency[]?  dependencies
--- @return string?                error_message
local function dependencies_from_manifest(manifest)
    return make_dependencies(manifest:get_dependencies())
end

--- Build direct dependencies and exact package versions from a lockfile.
--- Project performs this translation so DependencyManager never needs to know
--- the lockfile's schema or record structure.
--- @param lockfile  Artemis.Lockfile
--- @return Artemis.Dependency[]?  dependencies
--- @return table<string, string>? exact_versions
--- @return string?                error_message
local function dependencies_from_lockfile(lockfile)
    local locked_records = lockfile:get_dependencies()
    local declarations = {}
    local exact_versions = {}

    for name, record in pairs(locked_records) do
        exact_versions[name] = record.version
        if record.direct then
            if type(record.constraint) ~= "string" or not record.constraint:match("%S") then
                return nil, nil, string.format("Direct dependency '%s' has no version constraint in the lockfile.", name)
            end
            declarations[name] = record.constraint
        end
    end

    local dependencies, dependency_error = make_dependencies(declarations)
    if not dependencies then
        return nil, nil, dependency_error
    end

    return dependencies, exact_versions
end

