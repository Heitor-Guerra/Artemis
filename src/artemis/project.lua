--- Create a Project and load its manifest.
--- The constructor creates the runtime manager but does not download or compile
--- a runtime. The dependency manager is configured after a runtime is selected.
--- Call sync() to ensure the requested runtime and dependencies are installed.
--- @param project_root  string                  Project directory.
--- @param options?      Artemis.ProjectOptions
--- @return Artemis.Project?  project
--- @return string?           error_message
function Project.new(project_root, options)
    if type(project_root) ~= "string" or not project_root:match("%S") then
        return nil, "Project root must be a non-empty path."
    end

    options = options or {}
    if type(options) ~= "table" then
        return nil, "Project options must be a table."
    end

    local root = Path.absolute_directory(project_root)
    if not root then
        return nil, string.format("Project directory '%s' does not exist or cannot be accessed.", project_root)
    end

    local requested_manifest_path = options.manifest_path
    if requested_manifest_path == nil and type(options.manifest) == "table" then
        requested_manifest_path = options.manifest.path
    end
    requested_manifest_path = requested_manifest_path or Manifest.DEFAULT_FILENAME

    if type(requested_manifest_path) ~= "string" or not requested_manifest_path:match("%S") then
        return nil, "Manifest path must be a non-empty string."
    end

    local manifest_path = project_path(root, requested_manifest_path)
    local manifest = options.manifest

    if manifest == nil then
        local load_error
        manifest, load_error = Manifest.load(manifest_path)
        if not manifest then
            return nil, load_error
        end
    elseif type(manifest) ~= "table" or type(manifest.validate) ~= "function"
        or type(manifest.save) ~= "function" or type(manifest.get_dependencies) ~= "function" then
        return nil, "options.manifest must be a valid Artemis.Manifest instance."
    end

    local valid, validation_error = manifest:validate()
    if not valid then
        return nil, string.format("Invalid project manifest:\n%s", validation_error)
    end

    -- Keep all manifest writes anchored to this project's manifest file.
    manifest.path = manifest_path

    local requested_lockfile_path = options.lockfile_path or Lockfile.DEFAULT_FILENAME
    if type(requested_lockfile_path) ~= "string" or not requested_lockfile_path:match("%S") then
        return nil, "lockfile_path must be a non-empty path."
    end
    local lockfile_path = project_path(root, requested_lockfile_path)

    local metadata_dir = options.metadata_dir or ".artemis"
    if type(metadata_dir) ~= "string" or not metadata_dir:match("%S") or Path.is_absolute(metadata_dir) then
        return nil, "metadata_dir must be a non-empty relative path."
    end

    local runtime_options = copy_options(options.runtime_options)
    runtime_options.cache_dir = options.cache_dir or runtime_options.cache_dir

    local runtime_manager, runtime_error = RuntimeManager.new(runtime_options)
    if not runtime_manager then
        return nil, runtime_error
    end

    local dependency_options = copy_options(options.dependency_options)
    dependency_options.cache_dir = runtime_manager.cache_dir
    dependency_options.metadata_dir = metadata_dir
    dependency_options.lua_version = manifest.data.lua

    if options.tree ~= nil then
        dependency_options.tree = options.tree
    end
    if options.luarocks ~= nil then
        dependency_options.luarocks = options.luarocks
    end
    if options.luarocks_config ~= nil then
        dependency_options.luarocks_config = options.luarocks_config
    end

    local self = setmetatable({}, Project)
    self.root = root
    self.manifest = manifest
    self.manifest_path = manifest_path
    self.lockfile_path = lockfile_path
    self.runtime_manager = runtime_manager
    self.cache_dir = runtime_manager.cache_dir
    self.metadata_dir = metadata_dir
    self._dependency_options = dependency_options

    return self
end

--- Create or recreate DependencyManager with the selected runtime prefix.
--- LuaRocks uses this prefix to find the matching interpreter, headers, and
--- libraries when building native rocks. Project supplies configuration only;
--- dependency declarations are passed separately to each manager operation.
--- @param lua_dir?  string  Exact Lua installation prefix.
--- @return Artemis.DependencyManager?  manager
--- @return string?                     error_message
function Project:_create_dependency_manager(lua_dir)
    local dependency_options = copy_options(self._dependency_options)
    dependency_options.cache_dir = self.cache_dir
    dependency_options.metadata_dir = self.metadata_dir
    dependency_options.lua_version = self.manifest.data.lua
    dependency_options.lua_dir = lua_dir

    return DependencyManager.new(self.root, dependency_options)
end

--- Return the dependency manager, creating a configuration-only instance when needed.
--- Listing or removing rocks does not require installing the selected Lua runtime.
--- @return Artemis.DependencyManager?  manager
--- @return string?                     error_message
function Project:_ensure_dependency_manager()
    if self.dependency_manager then
        return self.dependency_manager
    end

    local manager, manager_error = self:_create_dependency_manager()
    if not manager then
        return nil, manager_error
    end

    self.dependency_manager = manager
    return manager
end

--- Ensure that the requested Lua runtime is installed and selected.
--- If requested_version is an exact version from a valid lockfile, Artemis uses
--- that release instead of resolving the newest patch in the manifest's series.
--- The runtime is shared from the Artemis cache rather than copied into the project.
--- @param requested_version?  string  Exact locked runtime version; defaults to manifest requirement.
--- @return boolean  success
--- @return string?  error_message
--- @return string?  installed_version
function Project:install_runtime(requested_version)
    requested_version = requested_version or self.manifest.data.lua

    local installed, install_error, version = self.runtime_manager:install(requested_version)
    if not installed or not version then
        return false, install_error
    end

    local runtime_path, path_error = self.runtime_manager:get_install_path(version)
    if not runtime_path then
        return false, path_error
    end

    local executable, executable_error = self.runtime_manager:get_executable(version)
    if not executable then
        return false, executable_error
    end

    local dependency_manager, dependency_error = self:_create_dependency_manager(runtime_path)
    if not dependency_manager then
        return false,
            string.format("Lua %s is installed, but LuaRocks could not be configured for it: %s", version,
                dependency_error)
    end

    self.dependency_manager = dependency_manager
    self.runtime_version = version
    self.runtime_path = runtime_path
    self.lua_executable = executable

    return true, nil, version
end

--- Synchronize the project environment with its manifest and lockfile.
--- A valid existing lockfile is authoritative: its exact Lua runtime and rock
--- versions are installed. If no lockfile exists, or its direct inputs no longer
--- match the manifest, LuaRocks resolves the manifest and Artemis writes a new lock.
--- @return boolean  success
--- @return string?  error_message
--- @return string?  installed_version
function Project:sync()
    local valid, validation_error = self.manifest:validate()
    if not valid then
        return false, validation_error
    end

    local active_lockfile
    if FileSystem.file_exists(self.lockfile_path) then
        local loaded_lockfile, load_error = Lockfile.load(self.lockfile_path)
        if not loaded_lockfile then
            return false,
                string.format("Could not load Artemis lockfile '%s': %s", self.lockfile_path, load_error)
        end

        local matches_manifest, mismatch_reason = loaded_lockfile:matches_manifest(self.manifest)
        if matches_manifest then
            active_lockfile = loaded_lockfile
        else
            -- Match uv's default sync behavior: a stale lock is refreshed from
            -- the current manifest instead of installing an incompatible graph.
            self._stale_lockfile_reason = mismatch_reason
        end
    end

    local requested_runtime = active_lockfile and active_lockfile.data.project.runtime or nil
    local runtime_ready, runtime_error, version = self:install_runtime(requested_runtime)
    if not runtime_ready then
        return false, runtime_error
    end

    if active_lockfile then
        local dependencies, exact_versions, conversion_error = dependencies_from_lockfile(active_lockfile)
        if not dependencies or not exact_versions then
            return false, conversion_error
        end

        local dependencies_ready, dependency_error = self.dependency_manager:install(dependencies, exact_versions)
        if not dependencies_ready then
            return false, dependency_error
        end

        local versions_match, version_error = self.dependency_manager:verify_versions(exact_versions)
        if not versions_match then
            return false, version_error
        end

        self.lockfile = active_lockfile
        return true, nil, version
    end

    -- No usable lockfile: resolve the declarations from the manifest, then
    -- capture the resulting direct and transitive versions for the next sync.
    local dependencies, conversion_error = dependencies_from_manifest(self.manifest)
    if not dependencies then
        return false, conversion_error
    end

    local dependencies_ready, dependency_error = self.dependency_manager:install(dependencies)
    if not dependencies_ready then
        return false, dependency_error
    end

    --- @type Artemis.InstalledRock[]?
    local installed_rocks = {}
    if next(self.manifest:get_dependencies()) ~= nil then
        local list_error
        installed_rocks, list_error = self.dependency_manager:list_installed()
        if not installed_rocks then
            return false, list_error
        end
    end

    if not installed_rocks then
        return false, "Installed Rocks could not be resolved."
    end
    local generated_lockfile, lock_error = Lockfile.from_installed(
        self.manifest,
        installed_rocks,
        {
            runtime_version = version,
            path = self.lockfile_path
        }
    )
    if not generated_lockfile then
        return false, lock_error
    end

    local saved, save_error = generated_lockfile:save(self.lockfile_path)
    if not saved then
        return false,
            string.format("Dependencies were installed, but the lockfile could not be saved: %s", tostring(save_error))
    end

    self.lockfile = generated_lockfile
    self._stale_lockfile_reason = nil
    return true, nil, version
end

--- Add a dependency to the manifest and install the resulting declarations.
--- The runtime is installed first to ensure native rocks target the selected Lua.
--- Manifest mutation and persistence are owned by Project, not DependencyManager.
--- @param package_name         string  LuaRocks package name.
--- @param version_constraint?  string  LuaRocks version constraint.
--- @return boolean  success
--- @return string?  error_message
function Project:add_dependency(package_name, version_constraint)
    local dependency, dependency_error = create_dependency(package_name, version_constraint)
    if not dependency then
        return false, dependency_error
    end

    local runtime_ready, runtime_error = self:install_runtime()
    if not runtime_ready then
        return false, runtime_error
    end

    local previous_constraint = self.manifest:get_dependency(dependency.name)
    local updated, update_error = self.manifest:set_dependency(dependency.name, dependency.constraint)
    if not updated then
        return false, update_error
    end

    local dependencies, conversion_error = dependencies_from_manifest(self.manifest)
    if not dependencies then
        if previous_constraint then
            self.manifest:set_dependency(dependency.name, previous_constraint)
        else
            self.manifest:remove_dependency(dependency.name)
        end
        return false, conversion_error
    end

    local installed, install_error = self.dependency_manager:install(dependencies)
    if not installed then
        if previous_constraint then
            self.manifest:set_dependency(dependency.name, previous_constraint)
        else
            self.manifest:remove_dependency(dependency.name)
        end
        return false, install_error
    end

    local saved, save_error = self.manifest:save(self.manifest_path)
    if not saved then
        if previous_constraint then
            self.manifest:set_dependency(dependency.name, previous_constraint)
        else
            self.manifest:remove_dependency(dependency.name)
        end

        return false, string.format(
            "Dependencies were installed, but the manifest could not be saved. The local tree may now contain the package. %s",
            save_error
        )
    end

    return true
end

--- Remove a dependency declaration and attempt to uninstall its rock.
--- The manifest change is owned and persisted by Project. LuaRocks may retain a
--- package when another installed rock still depends on it.
--- @param package_name  string  LuaRocks package name.
--- @return boolean  success
--- @return string?  warning_or_error
function Project:remove_dependency(package_name)
    local previous_constraint = self.manifest:get_dependency(package_name)
    if not previous_constraint then
        return false, string.format("Dependency '%s' is not declared in the manifest.", tostring(package_name))
    end

    local dependency, dependency_error = create_dependency(package_name, previous_constraint)
    if not dependency then
        return false, dependency_error
    end

    -- Removal does not need to install a runtime, but it still needs a manager
    -- configured for the project's LuaRocks tree.
    local manager, manager_error = self:_ensure_dependency_manager()
    if not manager then
        return false, manager_error
    end

    local removed, remove_error = self.manifest:remove_dependency(dependency.name)
    if not removed then
        return false, remove_error or string.format("Could not remove dependency '%s'.", dependency.name)
    end

    local saved, save_error = self.manifest:save(self.manifest_path)
    if not saved then
        self.manifest:set_dependency(dependency.name, previous_constraint)
        return false, save_error
    end

    return manager:uninstall(dependency.name)
end

--- Return the dependencies declared directly in the manifest.
--- @return table<string, string>
function Project:get_dependencies()
    return self.manifest:get_dependencies()
end

--- Return the rocks currently installed in the project's local LuaRocks tree.
--- @return Artemis.InstalledRock[]?  rocks
--- @return string?                   error_message
function Project:list_installed()
    local manager, manager_error = self:_ensure_dependency_manager()
    if not manager then
        return nil, manager_error
    end

    return manager:list_installed()
end

--- Return the installed rocks in the project's local tree.
--- This is currently a flat package listing, not a transitive dependency graph.
--- @return Artemis.InstalledRock[]?  rocks
--- @return string?                   error_message
function Project:tree()
    return self:list_installed()
end

--- Run a Lua script with the project's selected interpreter and LuaRocks paths.
--- Dependencies are synchronized before execution, similar to environment-aware
--- project runners. Script arguments must be provided as a string array.
--- @param script  string    Script path, relative to the project root or absolute.
--- @param args?   string[]  Arguments passed to the script.
--- @return boolean  success
--- @return string?  error_message
function Project:run(script, args)
    if type(script) ~= "string" or not script:match("%S") then
        return false, "Script path must be a non-empty string."
    end

    args = args or {}
    if type(args) ~= "table" then
        return false, "Script arguments must be an array of strings."
    end

    for index, argument in ipairs(args) do
        if type(argument) ~= "string" then
            return false, string.format("Script argument at index %d must be a string.", index)
        end
    end

    local script_path = project_path(self.root, script)
    if not FileSystem.file_exists(script_path) then
        return false, string.format("Script '%s' does not exist.", script)
    end

    local synchronized, sync_error = self:sync()
    if not synchronized then
        return false, sync_error
    end

    local path_exports, path_error = self.dependency_manager:path()
    if not path_exports then
        return false, path_error
    end

    local command_parts = {
        "cd " .. Process.shell_quote(self.root) .. " &&",
        "eval " .. Process.shell_quote(path_exports),
        "&& exec",
        Process.shell_quote(self.lua_executable),
        Process.shell_quote(script_path)
    }

    for _, argument in ipairs(args) do
        command_parts[#command_parts + 1] = Process.shell_quote(argument)
    end

    return Process.execute(table.concat(command_parts, " "))
end

